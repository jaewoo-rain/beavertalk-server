# -*- coding: utf-8 -*-
"""표현학습 문자열 정규화 — **판정하지 않는다.** (기획 §2-6 재설계, 2026-09-10)

## ⛔⛔ 이 모듈은 «퀴즈 통과» 를 결정하지 않는다 (사장님 결정)

한때 여기에 3갈래 판정기가 있었다 — 정확일치→통과 / 공통 어절 0→오답 / 그 사이→LLM.
**그 설계를 통째로 걷어냈다.** 문자열에 통과 결정권을 주면 두 가지가 반드시 따라온다:

  ① **포함 통과가 진도를 부풀린다.** 정답 `물` 에 "저는 물을 좋아해요" 가 통과했다.
     L2~L13 커리큘럼의 90%가 어휘(낱말 1개)라, 그 낱말이 든 아무 문장이나 통과가 된다.
     길이 상한으로 막아 봤지만 그건 증상 처방이었다.
  ② **«따라 말한 것» 과 «맞힌 것» 을 문자열로는 못 가른다.** 드릴이 «들려주고 따라 말하게»
     이므로 학습자가 항목을 그대로 말하는 순간이 통화에 수없이 많다. 직전 비버 발화를 보는
     앵무새 관문을 넣어 봤지만:
        1턴 창 → 재시도 경로가 샌다(B2 가 "다시 해봐" 면 표면형이 없다)
        2턴 창 → **정상 퀴즈가 막힌다**(B1 이 드릴이면 B2 퀴즈 정답이 차단된다)
     ⇒ 고정 N턴으로는 드릴과 퀴즈를 가를 수 없다. 필요한 것은 «지금 몇 번 문항의 어느
       단계인가» 인데, 문자열은 그걸 볼 수 없다.

⇒ **판정은 LLM 이, 쓰기는 파이썬이.** 사이드카가 전사를 읽고 «다룬 것·맞춘 것·틀린 것» 을
  번호로 돌려주고(`call_session._spawn_expression_progress`), 파이썬은 그 결과를 검증해
  DB 에 쓴다. 이 모듈에 판정 함수를 **다시 만들지 마라** — 위 ①②가 그대로 돌아온다.

## 그래서 여기 남은 것
서버가 여전히 문자열로 하는 일은 **판단이 아니라 사실 확인** 하나다 —
«비버가 이 문장을 말했나»(`call_session._note_covered_items`). 그 대조를 전사 잡음
(띄어쓰기·문장부호)에 안 흔들리게 하는 정규화만 여기 남는다.

⚠ 실제 호출자는 그 한 곳이고, **표현학습 경로에서만** 켜진다 — `normal` 통화는 생짜
  비교 그대로다(정규화를 켜면 그쪽 covered 검출 폭이 넓어져 재접지 쪽지가 바뀐다).

⛔ 이 모듈은 DB·LLM·도메인 모델을 모른다(어댑터 순수성). 표준 라이브러리만 쓴다 —
  `tests/test_quiz_judge.py` 가 **import 그래프로** 그걸 잠근다(소스 grep 이 아니다).
"""

from __future__ import annotations

import re
import unicodedata

# 걷어낼 것: 공백류 + 문장부호. ⛔ 한글 자모를 건드리지 않는다.
# ⚠ `\w` 를 쓰지 않는다 — 로케일에 따라 한글 포함 여부가 흔들린다. 버릴 것을 직접 적는다.
_PUNCT_RE = re.compile(r"[\s.,!?;:~…·\"'“”‘’()\[\]{}<>«»\-–—/\\|]+")


def normalize(text: str | None) -> str:
    """비교용 정규화 — **공백·문장부호만** 걷어낸다(NFC 정규화 포함).

    ⚠ NFC 를 거는 이유: 전사가 자모 분해형(NFD)으로 올 수 있고, 그러면 눈에 같은 글자가
      코드포인트로 달라 대조가 **조용히** 실패한다. macOS 계열 입력·일부 STT 의 실측 함정이다.
    ⛔ **조사·어미를 잘라내지 마라.** `안녕히 가세요` 와 `안녕히 계세요` 는 두 글자 차이인데
      **뜻이 반대다**(가는 사람에게 / 남는 사람에게) — 어미를 지우면 두 문장이 **같아진다.**
      지금은 판정을 안 하니 당장 사고가 나진 않지만, 이 함수를 쓰는 대조가 곧바로 틀린다.
    ⚠ 소문자화는 한다(라틴 문자 답변·영어 라벨 대비).
    """
    s = unicodedata.normalize("NFC", (text or "").strip())
    return _PUNCT_RE.sub("", s).lower()


# 한 어절 항목 뒤에 붙어도 «같은 낱말» 로 보는 꼬리(조사·어미). 빈 문자열 = 정확 일치.
# ⛔ **함부로 늘리지 마라.** 이 목록이 길어질수록 「개나리」류 접두 결합어가 다시 새어 들어온다.
#   늘릴 일이 생기면 그 낱말이 **오검출을 만들지 않는지** 먼저 시험으로 확인해라.
# ⚠ 활용 어미(-었어요·-습니다…)는 일부러 **안 넣었다** — 그걸 넣으면 어간 추출이 되고,
#   그건 이 모듈이 하지 않기로 한 일이다(모듈 독스트링).
_PARTICLES = frozenset({
    "", "은", "는", "이", "가", "을", "를", "에", "의", "도", "만",
    "과", "와", "로", "으로", "에서", "에게", "까지", "부터", "랑", "이랑",
    "요", "이요", "야", "아",
})


def mentions(text: str | None, label: str | None) -> bool:
    """전사에 그 항목이 **실제로 나왔나**(대조 전용 — 판정이 아니다).

    ## ⛔⛔ 부분문자열 하나로 끝내지 마라 — 이 설계가 이미 이름 붙인 실패다
    옛 대조는 `label in text` 였다. 그러면:

        항목 「물」  ·  학습자 발화 "어제 **선물**을 받았어요"   → 다뤘다로 잡힌다  ⛔

    ⇒ 그 항목이 «완료» 로 처리돼 **가르치지도 않고 건너뛰고**, DB 엔 drilled 로 남는다.
      L2 이상 커리큘럼의 90%가 어휘이고 그중 대부분이 1~2글자라, 여기가 **주 무대**다.
    ⚠⚠ 같은 결함을 이미 한 번 걷어냈다 — «정답 `물` 에 "저는 물을 좋아해요" 가 통과» 는
      **통과(pass) 경로**의 이야기였고, 그때 그 경로만 고치고 **대조(covered) 경로에는
      그대로 남겨 뒀다.** 두 경로가 같은 결함을 나눠 갖고 있었다.

    ## 그래서 낱말 경계를 요구한다
    · 여러 어절 항목(「안녕히 가세요」)  → 정규화 후 **부분문자열**. 어절 경계가 이미 있다
    · 한 어절 항목(「물」·「가다」)      → 어절이 그 항목으로 시작하고, **남는 꼬리가
      조사·어미**여야 한다(`_PARTICLES`)

    ## ⛔⛔ `startswith` 하나로 끝내지 마라 — 세 번째 되살아남을 막는 자리다
    이 결함은 이미 **두 번** 모양을 바꿔 돌아왔다(통과 경로 → 대조 경로 → **접두 결합어**).
    `startswith` 만 쓰면 뒤에 붙는 「선물」은 막지만 **앞에 붙는 것은 그대로 통과한다**:

        label「개」 ← "**개나리**가 피었어요"   → 어절이 「개」로 시작한다  ⛔ 오검출

    흔하다: 개→개나리·개인·개월·개발 / 눈→눈물 / 물→물건 / 말→말씀…
    ⇒ 라벨을 뗀 **꼬리가 조사·어미 목록에 있을 때만** 참으로 본다.
        「물을」→꼬리「을」 ✅   「물」→꼬리「」(정확일치) ✅
        「눈물이」→꼬리「물이」 ⛔   「개나리가」→꼬리「나리가」 ⛔

    ⚠ 동사·형용사는 활용이 **어미를 갈아치우므로**(들다→들었어요) 여기서 안 잡힌다. 그건
      **미검출**이고 안전한 방향이다 — 원형 그대로 나온 「가방을 들다」만 잡히면 된다.
      ⛔ 활용형까지 잡으려 들지 마라. 그 욕심이 정확히 오검출을 부른다.
    ⚠ **미검출은 안전하고 오검출은 아니다** — 못 잡으면 한 번 더 가르치면 되지만, 잘못 잡으면
      **가르칠 기회가 영영 사라진다**(`_note_covered_items` 독스트링의 보수성 규율 그대로).
    """
    lab = normalize(label)
    if not lab:
        return False
    raw = (text or "").strip()
    if not raw:
        return False
    if len((label or "").split()) > 1:
        return lab in normalize(raw)
    for word in raw.split():
        w = normalize(word)
        if w.startswith(lab) and w[len(lab):] in _PARTICLES:
            return True
    return False
