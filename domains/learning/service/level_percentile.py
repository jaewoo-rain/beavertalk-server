"""레벨 → "상위 N%" 표시값 매핑.

마이페이지가 레벨 옆에 "상위 45%" 를 띄운다. 이 값은 **실제 회원 분포에서 계산하지
않는다** — 계산 방식으로 가지 않은 이유:

  - 실사용자가 24명 남짓이다. 한 명이 승급하면 남의 백분위가 크게 흔들린다.
  - 같은 레벨이 여럿이면 전부 동률이라 "상위 45%" 가 뚝뚝 끊긴다.
  - 초기 사용자일수록 "상위 4%" 같은 과분한 숫자가 나와 의미가 없다.

그래서 **레벨별 고정 표** 로 둔다. 값이 흔들리지 않고, 서비스 정책(어느 레벨을
얼마나 상위로 보이게 할지)을 한 곳에서 조정할 수 있다.

값은 서비스 정책이라 언제든 바뀐다. 이 표만 고치면 되고 **앱 배포는 불필요**하다
(서버 응답으로 내려간다). 고칠 때 지켜야 할 것:
  - 레벨이 오를수록 percent 는 **작아져야** 한다(상위로 갈수록 소수).
  - 1~100 사이 정수. 0 이나 100 은 "상위 0%"·"상위 100%" 라 문구가 이상해진다.
  - 1~13 전 레벨을 채운다. 빠진 레벨은 None 이 되어 앱이 카드에서 그 줄을 숨긴다.
  (위 세 가지는 tests/test_mypage_integration.py 가 지킨다 — 표를 뒤집어 넣기 쉽다.)

관련 결정: 예전엔 "사용자에게 레벨·점수 비노출"(D2)이었으나 마이페이지 개편으로
**노출**로 바뀌었다. docs 마스터플랜 §0 D2 참고.
"""

from __future__ import annotations

from typing import Optional

# 레벨(1~13) → 상위 N%. 위 주의사항을 지켜 값만 갈아끼우면 된다.
#
# 초반(1~3단계)이 90 → 75 → 50 으로 크게 떨어지는 건 의도다. 실사용자 대다수가
# 진짜 초보라 그 구간에 몰려 있고, 한 단계 올랐을 때 체감이 커야 한다.
# 4단계부터는 5%p 씩 고르게 좁힌다.
LEVEL_TOP_PERCENT: dict[int, int] = {
    1: 90,
    2: 75,
    3: 50,
    4: 45,
    5: 40,
    6: 35,
    7: 30,
    8: 25,
    9: 20,
    10: 15,
    11: 10,
    12: 5,
    # 13 = "최상위권". 문구를 따로 만들면 30개 로케일을 다 손봐야 해서, 같은 뜻이
    # 통하는 최소값 1(=상위 1%)로 표현한다. 별도 라벨이 필요하면 여기 말고
    # 앱에서 level==maxLevel 을 특수 처리하는 편이 낫다.
    13: 1,
}


def top_percent(level_no: Optional[int]) -> Optional[int]:
    """레벨의 "상위 N%" 표시값. 레벨 미확정(레벨테스트 전)이면 None.

    표에 없는 레벨도 None 이다 — 없는 값을 지어내느니 앱이 그 줄을 숨기는 편이 낫다.
    """
    if level_no is None:
        return None
    return LEVEL_TOP_PERCENT.get(int(level_no))
