def build_leveltest_instruction(
    *,
    role: str,
    personality: str,
    locale: str,
    interests: list[str],
    name: str | None = None,
    target_language: str = "한국어",
    locale_label: str | None = None,
    close_tag: str = "",
) -> str:
    """레벨테스트 system_instruction — LLM 생성 0, 순수 문자열 조립.

    ⛔ Gemini 쪽(`core.persona_prompt.build_leveltest_instruction`)과 **인자가 같다** —
      호출부가 엔진 분기만으로 갈아탈 수 있어야 한다.
    ⚠ `close_tag` 는 받기만 하고 쓰지 않는다. 정본도 2026-08-02 부터 출력에 싣지 않는다
      (낭독 방지) — 하위호환으로 자리만 남긴 것이고 여기도 같게 둔다.
    """
    locale_label = locale_label or _LOCALE_LABEL.get(locale, _LOCALE_LABEL[_DEFAULT_LOCALE])
    interests_text = ", ".join(i for i in interests if i) or "일상"
    username = (name or "").strip() or "학습자"
    # 미등록 언어는 한국어 사다리로 떨어뜨린다(안전 기본값 — 정본과 같은 규칙).
    ladder = _LADDER.get(target_language, _LADDER_KO)
    return _TEMPLATE.format(
        role=role,
        personality=personality,
        locale_label=locale_label,
        username=username,
        target=target_language,
        interests_text=interests_text,
        ladder=ladder,
    )


