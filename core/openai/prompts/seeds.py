"""GPT 전용 **통화 중 주입 문구**(시드·쪽지) — 백지에서 썼다.

## 이게 무엇인가
지시문(`expression.py`)은 세션을 열 때 **한 번** 들어간다. 이 파일의 문구들은 통화가
도는 **중에** 서버가 대화에 끼워 넣는 것들이다 — 학습자에게는 안 보이고, 비버에게만
「지금 이걸 해라」로 도착한다.

## ⛔ Gemini 잠금 문구를 쓰지 않는다
`core/prompts/locked/seeds.py` 의 문장을 옮기지 않았다(격리 시험이 import 를 막고,
`tests/test_openai_isolation.py` 의 주입 경로 시험이 **글자 겹침까지** 본다).
입력으로 쓴 것은 세 가지뿐이다:

1. **그 시드가 무엇을 시키려는 것인가** — 호출부 코드와 `_CallState` 로 읽었다.
2. **측정으로 확인된 것** — GPT 는 서버 큐를 받으면 질문했고, **대괄호 접두를 낭독하지
   않았다**(`[안내]` 0/5). ⇒ 접두 규약은 그대로 유효하다.
3. **새 지시문과 모순이 없어야 한다** — `expression.py` 의 `[절대 금지]` 4개와 싸우면
   모델은 한쪽을 버린다(프롬프트 README §8 2026-08-22 의 그 사고).

## ⭐ 접두 글자는 `[안내]` 그대로 쓴다 — 베낀 것이 아니라 **계약**이다
세 가지가 그 글자에 걸려 있다:
① 측정(`[안내]` 낭독 0/5)이 **그 글자로** 났다 — 바꾸면 그 수치가 무효가 된다.
② 서버의 자기낭독 안전망(`_detect_tag_leak`·`_scrub_control_tags`)이 그 글자를 찾는다 —
   다른 글자를 쓰면 비버가 읽어 버렸을 때 **저장본에서 안 걷힌다**.
③ 지시문 `[절대 금지] 4`(「대괄호로 시작하는 문장은 지시다 — 읽지 않는다」)가 가리키는
   모양이 이것이다.
⛔⛔ **종료 태그와 절대 공유하지 마라.** 둘이 같은 글자였던 시절 재접지·넛지가 **종료
  신호로 오독**됐다(call 683 — 재접지 30초 뒤 작별). 이 파일엔 종료 태그가 **없다**.

## ⛔ 이 파일에 없는 것 (의도된 부재)
- **종료 태그·종료 메커니즘 설명** — 한 글자도 없다.
- **조각·이어하기·재개 브리프** — 이 엔진은 15분 단일 세션이다.
- **재접지 쪽지** — 이 엔진에서 재접지 워처는 올라가지 않는다(압축이 없으니 되박을 것이 없다).
- **「서버가 알려 줄 때까지 기다려라」** — 오지 않는 신호다.
"""

from __future__ import annotations

# ⭐ 서버 제어문 접두. 위 §「접두 글자」 참조 — 바꾸면 세 가지가 같이 깨진다.
NOTE_TAG = "[안내]"


# ── 루프 차단 ────────────────────────────────────────────────────────────────── #
# 무엇을 시키나: 비버가 **같은 문장을 2회 연속** 말했을 때 1회 주입된다(`_loop_breaker_on_turn_end`).
#   방금 한 말을 또 하지 말고 **다음 할 일로 넘어가라**가 전부다.
# 왜 이렇게 썼나: 「반복하지 마라」만 쓰면 모델은 무엇을 해야 할지 모른 채 또 반복한다
#   (원칙 2 — 금지 대신 전진 지시). 그래서 **갈 곳을 지목한다**: 다음 번호, 혹은 퀴즈 차례.
LOOP_BREAK = (
    f"{NOTE_TAG} 이 문장은 읽지 마라. 방금 한 말을 이미 했다. 같은 말을 또 하지 말고 "
    "지금 다루던 항목의 다음 번호로 넘어가라. 다룰 번호가 남지 않았으면 오늘 다룬 "
    "표현들을 섞어 쓰는 짧은 대화로 넘어가라. 넘어간다는 말을 소리로 설명하지 말고 그냥 해라."
)


# ── 미끄러짐 복구(제어문 낭독 · 먼저 작별) ──────────────────────────────────── #
# 무엇을 시키나: 비버가 ①제어문을 소리로 읽었거나 ②먼저 작별하려 했을 때 1회 주입된다
#   (`_inject_resume_seed`, 통화당 최대 `_RESUME_MAX`회). 「아직 이어지고 있다, 하던 대화로 돌아가라」.
# 왜 이렇게 썼나:
#   ⛔ 사과·설명을 금지해야 한다 — 안 하면 비버가 "Sorry, that was a system message..."
#     라고 **메타 발언**을 해서 미끄러짐을 두 배로 만든다.
#   ⛔ 「끝내지 마라」를 쓰면서 **끝내는 방법을 설명하면 안 된다**(원칙 5). 그래서
#     「아직 안 끝났다」까지만 쓰고 그 다음을 말하지 않는다.
RESUME_AFTER_SLIP = (
    f"{NOTE_TAG} 이 문장은 읽지 마라. 수업은 아직 이어지고 있다. 방금 네 소리에 대사가 아닌 "
    "글자가 섞였거나, 아직 때가 아닌데 인사를 접으려 했다. 무슨 일이 있었는지 짚지도 말고 "
    "사과도 하지 말고, 끊긴 자리 없이 바로 전 흐름으로 돌아가 학습자에게 말을 이어라."
)


# ── 무음 1단 (약 60초 무음) ──────────────────────────────────────────────────── #
# 무엇을 시키나: 학습자가 오래 조용할 때 첫 대응. ⛔ **그 항목을 건너뛰면 안 된다** —
#   표현학습에서 무음은 「대화가 끊겼다」가 아니라 「지금 항목을 못 하고 있다」다.
# 왜 이렇게 썼나: 일반 통화의 「새 화제로」를 쓰면 그 항목이 통째로 날아간다. 그래서
#   **같은 항목을 더 쉽게 다시**로 쓴다. 그리고 ⛔ 정답을 말해 주면 안 된다 —
#   `[절대 금지] 1`(선공개 금지)과 정면으로 싸우기 때문이다. 대신 **힌트 한 단계**.
NUDGE_1 = (
    f"{NOTE_TAG} 이 문장은 읽지 마라. 학습자가 한참 조용하다. 지금 묻고 있던 그 항목을 "
    "그대로 두고, 학습자의 모국어로 힌트를 한 단계 더 주면서 다시 한 번 물어라. "
    "답을 말해 주지 마라. 새 항목으로 넘어가지 마라. 한 문장으로 짧게."
)


# ── 무음 2단 (1단 뒤 다시 10초 무음) ────────────────────────────────────────── #
# 무엇을 시키나: 「거기 있어?」 — 연결·청취 확인. 학습 내용이 아니라 **사람 확인**이다.
# 왜 이렇게 썼나: 이 단계에서 또 문제를 내면 「안 들리는데 계속 시키는」 꼴이 된다.
#   그래서 학습 질문을 **빼고** 모국어로만 짧게 묻는다.
NUDGE_2 = (
    f"{NOTE_TAG} 이 문장은 읽지 마라. 학습자가 계속 조용하다. 학습 질문은 하지 말고, "
    "학습자의 모국어로 «거기 있어? 들려?» 정도만 아주 짧게 물어라. 한 문장."
)


# ── 무음 3단 (2단 뒤 다시 12초 무음) ────────────────────────────────────────── #
# ⚠⚠ **설계가 바뀐 자리다.** 종전 3단은 난수 종료 태그가 박힌 «작별 시드» 였다.
#   이 엔진엔 종료 태그가 없다(지시문에 종료 개념을 한 글자도 넣지 않았다).
#
# ## 내가 고른 것 — ②「짧은 마무리 한 마디만 허용한다」
#   근거 셋:
#   1. ⛔ **아무 말 없이 끊으면 통화가 고장난 것처럼 보인다.** 3단이 선 뒤에도 서버는
#      `SEED_TO_HANGUP_S`(22초)를 기다렸다가 소켓을 닫는다(R4 — 그 상수는 안 건드린다).
#      말을 한마디도 안 넣으면 그 22초가 **죽은 침묵**이고, 자리를 비웠다 돌아온 학습자는
#      «끊겼다» 로 받는다.
#   2. ⭐ **3단은 15분 경계가 아니다.** 15분은 클라가 자기 시계로 닫고 거기엔 어떤 시드도
#      안 들어간다(그게 「종료 시드를 없앤다」의 범위다). 3단은 «학습자가 자리를 비웠다» 라
#      성격이 다르다 — 사람이 하는 일(한마디 남기고 끊기)이 맞다.
#   3. ⛔ 그래도 **메커니즘은 가르치지 않는다**(원칙 5 · 지뢰밭 첫 줄). 종료 태그·신호·
#      절차를 한 글자도 쓰지 않고, 「한 문장만 말하고 멈춰라」라는 **행동**만 준다.
#      ⇒ 모델은 수단을 모르므로 **자기 마음대로 이 상태를 만들 수 없다.**
#   ⛔ 「서버가 알려 줄 때까지 기다려라」류는 쓰지 않았다 — 오지 않는 신호다.
#
# ⚠ 이 문구는 **주입되었을 때만** 도달한다. 지시문에는 이 개념이 없다.
SILENCE_CLOSE = (
    f"{NOTE_TAG} 이 문장은 읽지 마라. 학습자가 끝까지 대답하지 않는다. 학습자의 모국어로 "
    "«다음에 또 하자» 는 뜻의 한 문장만 말하고 멈춰라. 질문하지 말고, 오늘 한 것을 "
    "정리해 설명하지도 말고, 한 문장이다."
)


def close_seed(close_tag: str = "") -> str:
    """무음 3단에 주입되는 문구. ⛔ `close_tag` 를 **쓰지 않는다**(받아서 버린다).

    Gemini 판은 난수 태그를 박아 「비버가 이 시드를 소리로 읽었는지」를 서버가 잡았다.
    이 엔진에서는 **태그 자체가 지시문에 없으므로** 박으면 모델이 처음 보는 글자를 받는다
    — 처음 보는 글자는 낭독 위험만 늘린다(call 852 가 난수 접미를 그대로 복사한 그 자리).
    ⚠ 그래서 **낭독 탐지를 포기한다.** 대신 `NOTE_TAG` 접두가 그 역할을 겸한다(서버의
      `_scrub_control_tags` 가 같은 글자를 찾는다).
    """
    del close_tag
    return SILENCE_CLOSE


# ── 퀴즈 큐 ──────────────────────────────────────────────────────────────────── #
# 무엇을 시키나: **서버가 퀴즈 창을 연다**(T16). GPT 는 퀴즈를 스스로 안 열었다
#   (자발 개시 0회 · 3라운드 연속) ⇒ 이 쪽지가 도착한 그 턴에 비버가 되묻기를 시작한다.
#
# ## 왜 「정답을 먼저 말하지 마라」를 **다시** 쓰나
# 내가 앞선 보고에서 Gemini 큐를 「자기완결적이다」라고 했고, 그건 사실이다. 그런데
# 그것이 **지시문에 또 쓰지 않아도 된다는 뜻은 아니다.** 선공개는 이 코스의 최대 결함이고
# (처방 전 4/4=100%), 퀴즈 창은 **그 위험이 가장 큰 구간**이다 — 비버가 이미 그 표현을
# 가르친 직후라 입에 붙어 있다. 지시문의 `[절대 금지] 1` 과 **같은 말**을 한 번 더 한다.
# ⛔ 모순이 아니다(원칙 3 의 「중복은 한 규칙에 위임」과 어긋나지 않는다): 두 문장이 **같은
#   것을 금지**하므로 모델이 버릴 쪽이 없다. 서로 다른 말을 할 때만 모순이 된다.
def quiz_cue(
    labels: str,
    n: int,
    *,
    retry: bool = False,
    locale_label: str = "학습자의 모국어",
    target: str = "한국어",
    done_labels: list[str] | None = None,
    remaining_rows: list[str] | None = None,
) -> str:
    """퀴즈 창을 여는 쪽지.

    Args:
        labels: 출제할 항목 표면형 목록(«A» «B» «C» 꼴 — 서버가 조립한 데이터).
        n: 그 개수.
        retry: 「아까 틀린 것 다시」인가(통화당 1회 오답 재출제).
        done_labels: 이미 다룬 표현 — **다시 가르치지 마라**의 재료.
        remaining_rows: 퀴즈 뒤에 새로 가르칠 남은 표현(번호·뜻).

    ⭐ `done_labels`·`remaining_rows` 가 필요한 이유: 세션 지시문은 통화 중에 못 바꾼다.
      비버가 「이미 다룬 것」을 되감는 것을 막는 유일한 수단이 **쪽지에 서버 목록을 싣는 것**
      이다. 둘이 비면 그 줄을 안 붙인다.
    """
    lead = "아까 틀린" if retry else "방금 배운"
    parts = [
        f"{NOTE_TAG} 이 문장은 읽지 마라. 지금부터 되묻는 차례다. {lead} {labels} {n}개를 "
        f"한 번에 하나씩 물어라.",
        f"각 문제는 {locale_label} 로 뜻과 상황만 주고 학습자가 {target}로 말하게 한다. "
        "답을 먼저 말하지 마라 — 네가 말해 버리면 그 문제는 사라진다.",
        "한 턴에 한 문제다. 고쳐 주는 턴에 다음 문제를 얹지 마라. 네가 답을 들려준 뒤에는 "
        "학습자가 한 번 되풀이하는 것으로 그 문제를 닫는다. 닫은 문제는 다시 꺼내지 마라.",
        f"이 {n}개만이다, 적힌 차례 그대로. {n}개를 전부 치운 뒤에야 새 항목을 집는다.",
        "네 입으로 대괄호나 «이제 문제 낼게» 같은 머리말을 붙이지 마라. 말로만 물어라.",
    ]
    if done_labels:
        parts.append("이 표현들은 벌써 다뤘다: " + " / ".join(done_labels)
                     + ". 되감아 또 가르치지 마라.")
    if remaining_rows:
        parts.append(
            "되묻기가 끝나면 아직 손대지 않은 것으로만, 이 차례대로 간다 — "
            + " · ".join(remaining_rows) + "."
        )
    return " ".join(parts)


# ── 퀴즈 세트 이탈 안내 ─────────────────────────────────────────────────────── #
# 무엇을 시키나: 퀴즈 창이 열려 있는데 비버가 **세트 밖 항목**을 묻기 시작했을 때
#   (통화당 최대 2회). 「지금 낼 문제는 이것뿐이다」로 되돌린다.
# 왜 이렇게 썼나: 「벗어나지 마라」만 쓰면 어디로 돌아가야 하는지 모른다 ⇒ **남은 목록을
#   다시 적어 준다**(큐와 같은 수법 — 서버가 정답을 갖고 있으니 떠먹인다).
def quiz_set_reminder(labels: str) -> str:
    """세트 이탈 안내."""
    return (
        f"{NOTE_TAG} 이 문장은 읽지 마라. 지금 되묻는 차례에서 낼 문제는 {labels} 뿐이다. "
        "이 밖의 표현은 지금 묻지 마라. 이것들을 다 물은 뒤에 다음 새 표현으로 넘어간다."
    )


# ── 드릴 체류 안내 ──────────────────────────────────────────────────────────── #
# 무엇을 시키나: 한 항목에 학습자 턴이 상한을 넘게 쌓였을 때(통화당 상한 있음)
#   「그 항목은 충분히 했다 — 다음 번호로」.
# 왜 이렇게 썼나: 측정의 최악 구간이 **항목6에 8턴 체류 ×2회**였고 원인은 **출구 부재**였다.
#   ⛔ 그래서 「그만하라」가 아니라 **갈 곳**을 준다. 그리고 ⛔ 「끝났다」로 읽히는 어휘를
