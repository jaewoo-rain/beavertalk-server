"""GPT 전용 표현학습 지시문 — **백지에서 썼다**.

## ⛔ 이 파일의 출처
Gemini 지시문(`core/prompts/locked/*`·`core/prompts/editable/*`)의 문장을 **한 줄도
옮기지 않았다.** 격리 시험(`tests/test_openai_isolation.py`)이 import 를 기계로 막고,
문장은 아래 세 가지 입력만 보고 새로 썼다:

### (1) 도메인 사실 (DB·커리큘럼)
오늘의 표현 N개(번호·표면형·뜻·예문) · 퀴즈는 `quiz_group` 개마다 · 같은 항목 최대 3회
재시도 · 무음 3단(서버가 처리) · 학습자 모국어 · 목표어 · 캐릭터 페르소나.

### (2) 측정으로 확인된 교훈 (2026-10-03 생짜 15분 1통 + 처방 재측정)
| 지켜야 할 것 | 실측 |
|---|---|
| 정답을 먼저 말하지 않는다 | 처방 전 선공개 **4/4(100%)** → 처방 후 **0/4** |
| 번호 순서 + 목록 소진 뒤 **출구** | 출구가 없으면 항목6에 **8턴 체류 ×2회** |
| 끝내는 때를 **기다리지 않는다** | 이 엔진엔 종료 시드가 없다 — 기다리면 영원히 안 끝난다 |
| 안내·리액션은 학습자 **모국어** | 규칙만 주면 한국어로 나온다 ⇒ 여러 번 떠받친다 |
| 허용을 **턴 단위로 주면 턴을 통째로 쓴다** | call 1754: 비버 9턴 중 **t11·t13 이 라틴 0**(전부 한국어) · t7 혼합. 셋 다 **오답 피드백 턴**이었다 — 당시 규칙 3 의 허용 ②「학습자가 말한 한국어를 고쳐 줄 때」가 턴 단위라 모델이 그 턴 전체의 면허로 읽었다. ⇒ 허용을 **토막 단위**(적힌 표현·학습자 발화 인용)로 내리고, [진행] 턴 틀의 **문장마다 언어를 괄호로 박았다**(2026-10-07) |
| 한 턴에 질문 하나 | 「응답 2개 + 질문 3번」 위반 관측 |
| 반말 답은 맞은 게 아니다 | 가르친 표현 반말 **0/52**(지켜졌다 — 유지할 축) |
| 의역 정답을 틀렸다고 하지 않는다 | `alt_polite` **4/5 기각**(운영 1636 재현) |
| 서버 큐를 받아 질문하되 **태그를 읽지 않는다** | `[안내]` 낭독 **0/5**(지켜졌다) |

### (3) GPT 특성 — Gemini 와 다르게 쓴 이유
- 선질문 위반: Gemini **6.2%** vs GPT **100%** ⇒ **금지를 맨 앞에, 단독 블록으로.**
- 번호 순서: GPT 는 **혼자 지켰다**(드릴 1회차 이탈 0) ⇒ 번호 강제에 지면을 덜 쓴다.
- 퀴즈: GPT 는 **스스로 안 열었다**(0회·3라운드) ⇒ 「스스로 열라」고 쓰지 않고
  **「큐가 오면 그때」** 로만 쓴다. 안 하는 걸 시키면 다른 규칙과 모순이 생긴다.

## ⛔ 이 파일에 쓰지 않은 것 (의도된 부재)
- **종료·마무리·작별을 설명하는 문장** — 한 글자도 없다. 모델이 수단을 모르면 그 수단을
  못 쓴다. 과거 3건(706·852·870)이 전부 「종료를 가르쳤더니 스스로 끊었다」였다.
- **조각·이어하기·재개·압축·재접지** — 이 엔진엔 없는 개념이다.
- **톤 부사와 예시 대사** — 톤은 캐릭터(role/personality)가 소유한다. 예시 대사를 쓰면
  모델이 그걸 그대로 뱉는다.
- **제어 태그의 글자 모양** — 서버가 붙이는 접두를 「읽지 말라」고만 하고, 어떤 글자인지
  보여주지 않는다.
"""

from __future__ import annotations

# 한 턴에 말할 문장 수 상한. 길면 학습자가 못 따라오고 원가도 는다.
DEFAULT_MAX_SENTENCES = 3
# ⭐ 한 문장 단어 상한(2026-10-07, call 1757 실측). 문장 **수**만 묶었더니 모델이
#   「긴 문장 3개」로 채웠다 — t3 237자/15.1초 · t9 252자/13.6초 · t13 219자/13.7초
#   (라틴 191자 ≈ 38단어). 초보 학습자가 15초를 듣고만 있었다.
#   ⛔ 턴 상한은 이 값 × 문장 수로 **계산한다** — 두 수를 따로 박으면 서로 모순돼
#     모델이 한쪽을 버린다(프롬프트 README §8 2026-08-22 의 그 사고).
MAX_WORDS_PER_SENTENCE = 8
# 같은 항목을 몇 번까지 다시 시키나. 서버 상한과 같은 숫자여야 한다(출구가 어긋나면
# 「서버는 넘겼는데 비버는 안 넘어간」 상태가 된다).
DEFAULT_RETRY_LIMIT = 3


def _row(idx: int, item: dict, *, target: str) -> str:
    """항목 한 줄: `3. 고마워요 — 뜻: thank you — 예: "도와줘서 고마워요."`"""
    surface = str(item.get("obj") or "").strip()
    row = "%d. %s" % (idx, surface)
    des = str(item.get("des") or "").strip()
    if des:
        row += " — 뜻: %s" % des
    ex = str(item.get("ex") or "").strip()
    if ex:
        row += ' — %s 예: "%s"' % (target, ex)
    return row


def _items_block(items: list[dict], *, target: str) -> str:
    rows = [_row(i, it, target=target) for i, it in enumerate(items, start=1)]
    if not rows:
        rows = ["(오늘 다룰 표현이 없다)"]
    return "[오늘의 표현]\n" + "\n".join(rows)


def _quiz_numbers(total: int, group: int) -> list[int]:
    """퀴즈가 걸리는 번호 — `group` 개마다. 6개·3이면 [3, 6]."""
    if group <= 0:
        return []
    return [n for n in range(group, total + 1, group)]


def build_expression_instruction(
    *,
    role: str,
    personality: str,
    locale_label: str,
    items: list[dict],
    quiz_group: int,
    target_language: str = "한국어",
    name: str | None = None,
    level_note: str = "",
    max_sentences: int | None = None,
    retry_limit: int = DEFAULT_RETRY_LIMIT,
    face_rule: str = "",
    self_quiz: bool = False,
) -> str:
    """표현학습 통화의 system_instruction(순수 문자열 조립 — LLM 생성 0).

    Args:
        role·personality: 캐릭터 2필드(DB). 톤은 전부 여기 위임한다.
        locale_label: 학습자 모국어 이름(예 "English"). **안내·리액션의 언어다.**
        items: `[{obj, des, ex}, ...]` — 순서가 곧 번호다(서버 선별이 낸 순서).
        quiz_group: 몇 개마다 퀴즈인가. ⛔ 기본값을 주지 않는다 — 선별 상수와 한 곳에서만.
        level_note: 학습자 수준 한 줄(없으면 블록을 안 넣는다).
        retry_limit: 같은 항목 재시도 상한. 서버 상한과 같아야 한다.
        face_rule: 표정 블록(표정 OFF 면 빈 문자열 → 블록 자체가 안 붙는다).
    """
    total = len(items)
    sent = DEFAULT_MAX_SENTENCES if not max_sentences else max(1, int(max_sentences))
    learner = (name or "").strip() or "the learner"
    quiz_nums = _quiz_numbers(total, int(quiz_group or 0))
    quiz_where = (
        ", ".join(str(n) for n in quiz_nums) if quiz_nums else "(없음)"
    )

    blocks: list[str] = []

    # ── ① 절대 금지 — GPT 는 금지를 맨 앞에 둬야 지킨다(선질문 위반 100% → 처방 필요) ──
    blocks.append(
        "[절대 금지 — 다른 모든 지시보다 먼저 지킨다]\n"
        "1. 학습자가 그 번호에 **입을 떼기 전**에는 그 %(t)s 표현을 말하지 않는다. 네가\n"
        "   먼저 소리로 내면 그 항목은 그 자리에서 물어볼 거리가 없어진다.\n"
        "   ⛔ **묻는 턴에 답을 같이 말하는 것도 이 금지다** — 「%(t)s로 뭐라고 해?」와\n"
        "     정답을 한 턴에 붙이지 마라. 학습자가 **먼저** 말해야 한다.\n"
        "2. 한 턴에 질문은 **하나**다. 질문을 두 개 이어 붙이지 않는다.\n"
        "3. **네 말은 전부 %(l)s 다.** %(t)s를 입에 담는 자리는 **정답 표현을 들려주는\n"
        "   그 한 토막**뿐이다 — 그 밖에는 없다.\n"
        "   설명·상황·칭찬·핀잔·지적은 물론이고 「말해 봐」·「다시」·「좋아」처럼 차례를\n"
        "   알리는 짧은 말까지 전부 %(l)s 다.\n"
        "   ⛔ **한 턴을 통째로 %(t)s로 말하는 일은 없다.**\n"
        "   ⛔ 서버가 꽂아 주는 쪽지가 %(t)s로 적혀 있어도 이 규칙은 바뀌지 않는다 —\n"
        "     쪽지의 언어를 따라가지 마라.\n"
        "4. 대괄호로 시작하는 문장이 오면 그건 너에게 주는 지시다 — **소리로 읽지 않는다.**"
        % {"t": target_language, "l": locale_label, "r": int(retry_limit)}
    )

    # ── ②' 대화 지속 — ⛔ 종료 어휘를 **한 글자도** 쓰지 않는다 ───────────────────── #
    # 실측(2026-10-06 대본 통화 4통 중 **2통**): 비버가 서버보다 먼저 통화를 접었다.
    # ⭐ 사장님 지시: 「먼저 접지 말라고 하는 게 아니라 **사용자가 끝내려고 하더라도
    #   계속해서 이야기 이어가도록** 하게끔」 — 금지가 아니라 **할 일**로 쓴다.
    # ⛔⛔ 그리고 그게 유일하게 안전한 쓰기다. 내가 처음에 「작별 인사를 하지 마라」를
    #   넣었다가 격리 시험(test_prompt_file_has_no_close_protocol_vocabulary)에 걸렸고,
    #   그 시험이 맞다: 「종료 개념을 가르친 과거 3건(call 706·852·870)은 전부 모델이
    #   스스로 통화를 끊는 사고로 끝났다 — 수단을 모르면 그 수단을 못 쓴다.」
    #   ⇒ 부정문도 개념을 가르친다. 여기엔 그 어휘가 **없다**.
    # ⚠ 가장 센 함정: 커리큘럼에 **헤어질 때 쓰는 표현**이 들어 있다(생존회화 청크).
    #   그걸 가르치는 재료로 다루다가 미끄러진다 — 그 구분만 박는다.
    blocks.append(
        "[학습자를 놓지 않는다]\n"
        "네 일은 수업을 **계속 이어가는 것**이다.\n"
        "- 학습자가 「고마워」·「알겠어」·「이제 갈게」·「bye」라고 해도 **놓지 마라.**\n"
        "  네 성격대로 한마디 받고, **조금 더 하자고 붙잡고** 곧바로 다음 문제를 내라.\n"
        "- ⚠ 오늘 다루는 표현 중에 **헤어질 때 쓰는 말**이 있을 수 있다. 그건 **수업\n"
        "  재료**다 — 들려주거나 시킨 직후 바로 다음 번호로 가라.\n"
        "- 목록을 다 돌았으면 아래 [%(n)d번까지 다 돌았으면] 대로 이어간다.\n"
        "\n"
        "[수업과 상관없는 말]\n"
        "학습자가 수업 밖의 말을 하면(네가 무엇인지 묻기·딴 이야기) 이렇게 한다.\n"
        "- ① (%(l)s) 그건 지금 할 이야기가 아니라고 **한마디로 자른다.** 네 성격대로.\n"
        "- ② 바로 **직전 문제로 돌아가** 같은 질문을 다시 한다.\n"
        "⛔ 그 말에 대답해 주지 마라. 설명도, 되묻기도 하지 마라 — 한마디로 자르고 돌아간다."
        % {"n": len(items), "l": locale_label}
    )

    # ── ② 역할 ───────────────────────────────────────────────────────────────── #
    blocks.append(
        "[역할]\n"
        "너는 %s. 성격: %s\n"
        "%s를 배우는 %s 와 음성으로 통화한다. 학습자의 모국어는 %s 다.\n"
        "칭찬·핀잔·농담은 네 성격대로 한다."
        % (role or "a Korean conversation partner", personality or "warm and relaxed",
           target_language, learner, locale_label)
    )
    if level_note.strip():
        blocks.append("[학습자 수준]\n%s" % level_note.strip())

    # ── ③ 종이 ───────────────────────────────────────────────────────────────── #
    blocks.append(_items_block(items, target=target_language))

    # ── ④ 진행 — 번호 강제에 지면을 덜 쓴다(GPT 는 혼자 지켰다) ────────────────── #
    blocks.append(
        "[진행]\n"
        "1번부터 차례로 **한 번에 한 번호**만 낸다. 다룬 번호는 대괄호 지시가 되물을 때만\n"
        "다시 낸다. 모든 번호에 같은 틀을 쓰며, 아래 ①·② 밖의 말을 붙이지 않는다.\n"
        "\n"
        "⭐ **%(l)s 문장은 %(w)d단어 이하**, 한 턴은 정답 표현까지 합쳐 **%(wt)d단어 이하**다.\n"
        "앞의 괄호는 문장의 언어다 — 소리로 내지 않는다.\n"
        "\n"
        "▶ 문제를 낼 때 — 1문장\n"
        "  ① (%(l)s) 상황 없이 그 번호의 「뜻」을 %(t)s로 뭐라 하는지 묻는다. 「뜻」이 맨 뒤다.\n"
        "  묶인 번호도 쪼개지 않고 **전부를 적힌 순서대로 한 번에** 답하게 한다.\n"
        "\n"
        "▶ 그 번호가 요구한 내용 전체를 %(t)s로 답했을 때만\n"
        "  ① (%(l)s) 한 문장으로 짧게 인정한다.\n"
        "  ② 곧바로 다음 번호를 위 [문제를 낼 때] 틀로 낸다.\n"
        "\n"
        "▶ 입을 뗐지만 위가 아닌 **모든** 경우(틀림·모름·%(l)s로 말함·엉뚱한 소리)\n"
        "  — **첫 번째부터** 매번 같은 2문장\n"
        "  ① (%(l)s) 못 맞혔다는 한마디(네 성격대로)와 듣고 따라 하라는 말을 한 문장에.\n"
        "  ② (%(t)s) [오늘의 표현]에 적힌 그 번호 **표현 전체만 그대로** 한 번."
        % {"l": locale_label, "t": target_language,
           "r": int(retry_limit), "n": min(3, sent),
           "w": MAX_WORDS_PER_SENTENCE, "wt": MAX_WORDS_PER_SENTENCE * min(3, sent)}
    )

    # ── ⑤ 맞았나 — 의역 수용 + 반말 기각(둘 다 실측 근거가 있다) ────────────────── #
    blocks.append(
        "[맞았는지 보는 법]\n"
        "- 맞은 것 = 학습자가 **%(t)s로 말했고** 뜻이 통한다. 적힌 글자와 달라도 같은 뜻의\n"
        "  다른 %(t)s 표현이면 맞고, 발음이 조금 어긋난 것도 넘어간다.\n"
        "- ⛔ 못 맞힌 것: **%(l)s 로 뜻만 말한 것**(번역을 맞다고 하지 마라) · %(t)s가 아닌\n"
        "  소리 · 알아들을 수 없는 소리. 넘겨주지 마라.\n"
        "- 다만 **정중한 말씨로 가르친 표현을 반말로 답하면 맞은 것이 아니다.** 그때는\n"
        "  말씨를 올려 다시 말해 보게 한다."
        % {"t": target_language, "l": locale_label}
    )

    # ── ⑥ 퀴즈 — 서버 큐(기본) 또는 자가 개시(실험 `OPENAI_SELF_QUIZ`) ──────────── #
    # ⭐⭐ 실험(2026-10-06 사장님 지시)이 왜 필요한가:
    #   종전 측정 3라운드(19턴·13턴·52턴)에서 「자발 개시 0회」를 근거로 서버가 큐를
    #   쥔다고 결론했는데, **그 세 번 다 지시문이 「스스로 퀴즈를 시작하지 마라」였다.**
    #   ⇒ 시키지 않은 일을 안 한 것을 센 것이라 근거가 될 수 없다. GPT 에게 한 번도
    #     기회를 준 적이 없다. Gemini 는 받았고 실패했다(call_session.py:1317 — 대본에
    #     «3·6·9번 직후에만» 이 있는데도 4통화 중 3통화가 6·7·10번째에 냈고, 프롬프트를
    #     세 번 고쳐도 남았다). 그런데 GPT 는 번호 순서를 혼자 지켰고(이탈 0) 압축이
    #     없어 되감기 원인도 구조적으로 없다 ⇒ 재볼 값이 있다.
    if self_quiz:
        blocks.append(
            "[되묻기 — %(g)d개마다]\n"
            "**새 번호 %(g)d개를 다 내고 나면 그 %(g)d개를 바로 되묻는다** — 다음 새 번호로\n"
            "가기 **전**이다. 그다음 %(g)d개도 같다. 이 차례는 **네가 센다.**\n"
            "- 되묻기도 위 [진행] 틀 그대로다 — 상황을 주고 %(t)s로 말하게 한다.\n"
            "- 한 턴에 **한 문제**. %(g)d개를 전부 치운 뒤에 새 번호로 간다.\n"
            "- 묻는 차례는 낸 차례 그대로. 아직 안 낸 번호를 되묻기에 섞지 마라.\n"
            "- 되묻기를 시작한다는 말을 소리로 알리지 말고 그냥 물어라."
            % {"g": int(quiz_group or 0), "t": target_language}
        )
    else:
        blocks.append(
            "[퀴즈]\n"
            "%s번 항목을 끝낸 뒤에는 앞의 %d개를 되묻는 짧은 퀴즈 차례가 온다.\n"
            "그 차례는 **네가 정하지 않는다.** 대괄호로 시작하는 지시가 도착하면 그때 그 지시가\n"
            "말하는 번호들만 하나씩 되묻는다. 지시가 오기 전에는 되묻지 않고 진행을 계속한다."
            % (quiz_where, int(quiz_group or 0))
        )

    # ── ⑦ 목록을 다 돌았을 때 — 출구. ⛔ 「끝났다」로 읽히는 말을 쓰지 않는다 ───────── #
    blocks.append(
        "[%d번까지 다 돌았으면]\n"
        "같은 번호로 되돌아가지 않는다. 오늘 다룬 표현들을 **섞어서 쓰는 짧은 대화**로\n"
        "넘어간다 — 네가 상황을 하나 주고, 학습자가 그 표현 중 하나를 골라 말하게 한다.\n"
        "이 대화는 계속 이어간다. 학습자가 무엇을 더 해 보고 싶다고 하면 그걸 따른다."
        % total
    )

    if face_rule.strip():
        blocks.append(face_rule.strip())

    return "\n\n".join(blocks) + "\n"


def seed_opening(locale_label: str) -> str:
    """선톡 시드 — 서버가 첫 턴으로 밀어 넣는 user 텍스트(학습자에게 안 보인다).

    ⛔ 「시작하자」만 말하고 **1번 항목의 표현을 적지 않는다** — 시드에 표현이 들어가면
      그게 곧 선공개다.
    """
    return (
        "[지시] 지금 통화가 연결됐다. %s 로 짧게 인사하고, 1번 항목을 바로 시작한다. "
        "인사에 오늘 배울 표현을 미리 말하지 않는다." % locale_label
    )


def first_sentence(text: str, *, limit: int = 220) -> str:
    """수준 서술에서 **첫 문장만** 꺼낸다(나머지는 같은 말의 반복이었다 — 지면 낭비).

    ⚠ 호출부(realtime)가 조립한 긴 프로파일을 그대로 싣지 않기 위한 순수 함수다.
    """
    head = (text or "").strip().splitlines()[0] if (text or "").strip() else ""
    for mark in (". ", "。", "! ", "? "):
        idx = head.find(mark)
        if idx > 0:
            head = head[: idx + 1]
            break
    return head[:limit].strip()
