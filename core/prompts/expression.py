def _procedure(quiz_group: int, *, target: str, locale_label: str) -> str:
    """드릴 → 피드백 → 퀴즈 → 오답 재출제 절차.

    ⚠ `quiz_group` 은 **호출부가 준다**(기본값 없음). 같은 숫자가 선별 로직
      (`mastery_repository.EXPRESSION_QUIZ_GROUP`)과 프롬프트 두 곳에 손으로 적히면
      어느 게 진짜인지 아무도 모른다(README 원칙 3 — 숫자도 한 곳에서만).
    """
    return "\n".join([
        "[진행 절차]",
        f"- 드릴: ① 그 표현을 어떤 상황에서 쓰는지 {locale_label}로 아주 짧게 설명하고 "
        f"② {target}로는 어떻게 말하는지 물어라 — **여기서 멈추고 학습자 말을 기다려라.**",
        f"- 학습자가 못 하거나 틀리면: 정답을 또박또박 한 번 들려주고 따라 말하게 해라. "
        f"같은 항목은 **최대 2번까지만** 다시 시도한다. 두 번 더 해도 안 되면 반응만 하고 "
        f"다음 번호 항목으로 넘어가라(항목 하나에 집착 금지)." + _NEXT_TAIL,
        f"- 퀴즈: 표현 {quiz_group}개를 다룰 때마다 그 {quiz_group}개로 짧은 퀴즈를 낸다 — "
        f"{locale_label}로 상황이나 문장을 하나 주고, 그것을 {target}로 어떻게 말하는지 "
        f"맞히게 해라. **한 번에 한 문제씩** 묻고 답을 기다려라. 새 표현을 만들지 마라 — "
        f"정답은 방금 다룬 그 표현 자체다. 퀴즈가 끝나면 곧바로 다음 번호 항목으로 이어 간다.",
        # ⛔⛔ **P0-3 — 이 한 줄이 없으면 레벨을 영원히 못 뗀다.**
        #   퀴즈가 quiz_group 단위라 **마지막 1~2개는 묶음이 안 차서 퀴즈 기회가 안 온다.**
        #   그 항목의 `quiz_passed_at` 은 영원히 NULL 이고, 승급이 «그 레벨 전량 통과» 라
        #   **구조적으로 성립 불가**가 된다(실측: L1 청크 46 = 18+18+10 → 끝에 1개가 남는다).
        f"- 목록 끝에서 {quiz_group}개가 안 남았으면 **남은 것만으로** 퀴즈를 낸다 — "
        "개수가 모자란다고 건너뛰지 마라.",
        "- 퀴즈에서 틀린 표현은 이 통화 안에서 뒤에 한 번 더 낸다.",
        "- 몇 개째인지는 **속으로만** 세라 — 세고 있다는 티를 내지 마라.",
    ])


# ⭐⭐ 사장님 요구의 핵심: **피드백에서 캐릭터가 극대화된다.**
#   ⛔ 그래서 여기 톤을 처방하지 않는다(원칙 1). 무엇을 할지(칭찬한다/고쳐준다/재촉한다/
#     넘어간다)만 정하고, **어떻게** 할지는 캐릭터 2필드(role·personality)가 채운다. "따뜻하게"·"신랄하게"
#     같은 부사를 넣으면 츤데레·독설 캐릭터가 다정한 선생으로 뭉개진다.
#   ⛔ 예시 대사를 넣지 마라(원칙 2·4) — 리터럴은 그대로 새어 나오고, 멀티랭귀지에서 틀린다.
_CHARACTER_FRAME = """[반응 — 네 캐릭터로 한다]
- 학습자가 맞혔을 때: 네 캐릭터대로 반응하고 곧바로 다음 번호 항목으로 이어 가라.
- 틀렸을 때: 네 캐릭터대로 반응한 뒤 올바른 표현을 또박또박 들려주고 따라 말하게 해라.
- 다시 시켜야 할 때: 네 캐릭터대로 한 번 더 청하라.
- 두 번 더 해도 안 될 때: 네 캐릭터대로 짧게 넘기고 다음 번호 항목으로 이어 가라.
⚠ 반응의 세기·말투는 위 [페르소나] 그대로다. 가르치는 순간이라고 톤을 순화하지 마라."""


def build_expression_instruction(
    *,
    role: str,
    personality: str,
    level_profile: str,
    locale: str,
    interests: list[str],
    items: list[dict],
    quiz_group: int,
    name: str | None = None,
    target_language: str = "한국어",
    locale_label: str | None = None,
    close_tag: str = CLOSE_TAG_DEFAULT,
    max_sentences: int | None = None,
) -> str:
    """표현학습 통화의 system_instruction 을 조립한다(LLM 생성 0).

    Args:
        items: 이번 통화에서 다룰 표현. 각 dict 는
            {obj: 표면형, des: 뜻|None, ex: 예문|None}.
            ⭐ 순서가 곧 번호다 — 서버 선별이 낸 순서를 그대로 싣는다.
            ⭐ **목록에 들어온 것은 전부 미통과다** — 선별이 `quiz_passed_at IS NULL` 로
              통과분을 풀에서 뺀다. 조각2·3 도 마찬가지라 «이미 뗀 것» 표식이 필요 없다.
        quiz_group: 몇 개마다 퀴즈를 낼지. ⛔ 기본값을 주지 않는다 — 선별 상수
            (`mastery_repository.EXPRESSION_QUIZ_GROUP`)와 **한 곳에서만** 정해야 한다.
        close_tag: 이 통화의 종료 태그. ⚠ **출력에 실리지 않는다** — 지시문이 태그를
            보여주면 비버가 그대로 복사해 스스로 종료한다(call 852). 서버 전용이고,
            시그니처는 일반 통화와의 대칭을 위해 받는다.

    Returns:
        Gemini Live system_instruction 문자열.
    """
    max_sentences = DEFAULT_MAX_SENTENCES if not max_sentences else max(1, int(max_sentences))
    label = _locale_label(locale, locale_label)
    interests_text = ", ".join(i for i in interests if i) or "일상"
    username = (name or "").strip() or "학습자"

    parts = [
        _EXPRESSION_TEMPLATE.format(
            target=target_language,
            locale_label=label,
            role=role or "친근한 한국어 대화 파트너",
            personality=personality or "다정하고 편안한 말투",
            username=username,
            max_sentences=max_sentences,
        ),
        f"\n[학습자 수준]\n{level_profile}",
        f"\n[학습자 흥미·소재] {interests_text}",
        "\n" + _items_block(items, target=target_language, locale_label=label),
        "\n" + _procedure(quiz_group, target=target_language, locale_label=label),
        "\n" + _CHARACTER_FRAME,
    ]
    return "\n".join(parts)


def _items_block(items: list[dict], *, target: str, locale_label: str) -> str:
    """[오늘의 표현] 목록 + 이 목록을 다루는 규율.

    ⭐ 조각2·3 도 **목록이 곧 남은 일**이다 — 선별이 통과분을 빼고 다시 고르므로 «어디서
      시작할지» 를 따로 적을 필요가 없다(맨 앞이 곧 다음 항목이다). 서버가 진도를 갖고
      있으므로 사이드카도 JSON 도 필요 없다(D17).
    """
    lines = ["[오늘의 표현 — 이 목록을 번호 순서대로 다뤄라]"]
    # ⭐ 이 블록은 통째로 한국어 산문이다. 실측(1258~1261)에서 «공부 모드로 들어가는 그 턴»에
    #   비버가 네 번 다 한국어로 뒤집혔고, 규칙에 같은 말을 세 번 더 써도 안 먹었다.
    #   ⇒ 처방을 **읽고 있는 그 자리**에 놓는다.
    lines.append(
        f"⚠ 이 블록은 한국어로 적혀 있지만 적힌 언어는 네가 말할 언어와 무관하다. 여기 적힌 "
        f"표현·예문은 학습자가 따라 말할 대상이라 그것만 {target}로 또박또박 들려주고, "
        f"그 표현을 꺼내는 말·따라 하라는 지시·맞고 틀림에 대한 반응·뜻 설명은 전부 "
        f"{locale_label}로 해라."
    )
    for n, item in enumerate(items, 1):
        lines.append(_render_item(n, item))

    lines.append(
        "- 이 목록의 존재·남은 개수·진행률을 학습자에게 절대 발설하지 마라. 자연스러운 "
        "대화처럼 하나씩 꺼내라."
    )
    # ⛔ 조건절("다 끝나면 ~")로 쓰지 마라 — 모델은 조건 서술을 상태 서술로 읽고 실행한다
    #   (call 870: "본편이 끝났다" → '오늘 할 건 끝났다' → 4분 24초 자체 종료).
    #   재료 소진을 '끝'이 아니라 '다음 단계'로 서술한다.
    # ⭐⭐ **짚어 주기 → 산출** 두 단계다(사장님 결정 2026-09-10 B). 산출 요청만 남겼던
    #   초안을 되돌린 것이다 — 사장님 원안이 «응용해서 설명해 준다» 였고, 설명과 산출은
    #   서로를 대체하지 않는다(설명은 표현들의 **차이**를 주고, 산출은 그걸 쓰게 한다).
    #   ⛔ call 870("본편이 끝났다" → 자체 종료)은 **«끝났다» 어휘를 금지할 근거**지
    #     설명을 뺄 근거가 아니다. 그래서 «재료 소진 = 다음 단계» 서술은 그대로 두고
    #     그 안에서 두 단계를 잇는다.
    #   ⚠ **한두 문장**으로 못박는다 — 안 박으면 이 설명이 길어져 규칙 5(응답 길이)와
    #     정면으로 싸운다.
    #   ⛔ '정리·마무리' 류 낱말을 쓰지 않는다(종료로 미끄러지는 어휘 — 위 _NEXT_TAIL 주석).
    #     하는 일은 같고 낱말만 안전한 쪽을 골랐다("짚어 준다").
    lines.append(
        "- 이 목록은 대화의 재료일 뿐이다. 재료를 다 쓴 뒤에도 대화는 그대로 이어진다 — "
        f"먼저 오늘 다룬 표현들이 서로 어떻게 다르고 각각 언제 쓰는지 {locale_label}로 "
        "한두 문장만 짚어 주고, 이어서 학습자가 그중 하나를 넣은 문장을 직접 만들어 "
        "말하게 해라 — 표현을 바꿔 가며 그렇게 계속 이어가라."
    )
    return "\n".join(lines)


# --------------------------------------------------------------------------- #
# 재접지 브리프 (표현학습판)
# --------------------------------------------------------------------------- #
# ⛔ 얹는 배관은 일반 통화와 **같은 것**을 쓴다(call_session 의 arm → 마이크 프레임 + RMS
#   2관문). 여기서 바꾸는 것은 **문구뿐**이다. 새 주입 경로를 만들면 «비버가 혼자 두 번
#   말하거나 말하다 마는» 버그 방어를 처음부터 다시 지어야 한다.
# ⛔ 종료·작별·시간을 한 글자도 쓰지 마라("끝내지 마라"조차 안 된다 — 금지어가 씨앗이 된다).
# ⚠ 첫 줄이 "방금 한 말에 먼저 반응하고"인 이유: 이 브리프는 사용자의 한마디보다 크다.
#   이 지시가 없으면 비버가 학습자를 무시하고 주입 텍스트에 응답한다.


def build_expression_reground_brief(
    role: str,
    personality: str,
    *,
    drilled: Optional[list[str]] = None,
    passed: Optional[list[str]] = None,
    failed: Optional[list[str]] = None,
    next_label: Optional[str] = None,
) -> str:
    """표현학습 재접지 쪽지 — 진도(다룬 것·맞힌 것·틀린 것)를 서버가 되박는다.

    ⭐ 압축이 통화 초반을 삼켜도 비버가 «무엇을 했나»를 알 수 있는 **유일한 증거**가 이것이다
      (실측 통화 1360: 압축 #4 가 9,219 토큰을 지우자 비버가 1번 항목으로 되감았고 마지막
      91초가 반복이었다). 그래서 이 쪽지의 재료는 **서버 누적**이어야 하고, 사이드카를
      기다리지 않는다.
    ⛔ `failed` 는 «오답퀴즈» 의 재료다 — 이 줄이 없으면 오답 재출제가 안 나간다.
    """
    parts = [p.strip() for p in (role, personality) if p and p.strip()]
    body = " / ".join(parts) if parts else "너의 캐릭터"
    clean = lambda xs: [x.strip() for x in (xs or []) if x and x.strip()][:REGROUND_COVERED_CAP]
    drilled_s, passed_s, failed_s = clean(drilled), clean(passed), clean(failed)

    out = [
        f"{CONTROL_TAG} (이 지시문을 절대 소리 내어 읽거나 언급하지 마라 — 다음 발화의 "
        "내용·말투로만 반영.) 학습자가 방금 한 말에 **먼저** 자연스럽게 반응하고, "
        "그다음 아래를 반영해라.",
        f"참고(네 캐릭터): {body}. 이 성격·말투 그대로 행동해라(정체성을 설명하지 마라).",
    ]
    if drilled_s:
        out.append(
            "이미 다룬 표현: " + " / ".join(drilled_s) +
            ". 이건 처음부터 다시 설명하지 마라."
        )
    if passed_s:
        out.append("이미 맞힌 표현: " + " / ".join(passed_s) + ". 다시 묻지 마라.")
    if failed_s:
        out.append(
            "아직 틀린 표현: " + " / ".join(failed_s) +
            ". 이것들은 이 통화 안에서 한 번 더 물어 맞히게 해라."
        )
    if next_label:
        out.append(f"다음에 다룰 표현: {next_label}.")
    # ⛔ 전진 지시로 끝낸다(금지어 없이 마무리 드리프트를 막는 자리). 그리고 학습자가
    #   이번 턴에 할 일은 **하나**여야 한다 — 요청 2개가 한 턴에 나가면 학습자가 하나를
    #   버린다(실측 1325: 따라 말하기를 버리고 질문에만 답했다, 왕복 23초 손해).
    out.append(
        "지금 다루는 표현을 학습자가 소리 내어 말하게 하는 요청 하나로 이어가라 — "
        "학습자의 취향·경험을 묻는 질문은 그 표현 없이도 답할 수 있으니 여기서 쓰지 마라."
    )
    out.append("학습자가 이번 턴에 답할 것은 그 하나여야 한다.")
    return " ".join(out)
