# 항목 렌더 · 진행 절차 · 캐릭터 4상황 틀
# --------------------------------------------------------------------------- #
def _render_item(n: int, item: dict) -> str:
    """표현 한 줄: `{n}. {surface}` + 뜻/예문 꼬리.

    ⭐ 예문은 **있을 때만** 붙인다. L1 생존 청크는 `examples` 가 전 언어에서 0개인데
      (실측 — mastery_repository.first_example 이 None 을 돌려준다), 청크는 표면형 자체가
      문장이라 예문 없이 가르칠 수 있다. ⛔ 여기서 "예문은 네가 만들라"로 폴백하지 마라 —
      통문장을 통째로 익히게 하는 항목에 즉석 예문을 붙이면 분해 설명으로 샌다.

    ⛔⛔ **«(통과)» 표식을 되살리지 마라**(2026-09-10 QA 로 제거). 초안은 조각2·3 에서
      이미 뗀 항목에 표식을 붙이려 했는데, 그 표식이 **어느 조각에서도 출력되지 않았다**:
      선별이 `quiz_passed_at IS NULL` 로 통과분을 **풀에서 아예 뺀다** ⇒ 목록에 들어오는
      항목은 정의상 전부 미통과다. 동작은 우연히 맞았지만 죽은 분기가 다음 사람을 속인다.
      ⭐ 조각 승계는 표식이 아니라 **목록 그 자체**가 한다 — 목록이 곧 «남은 일» 이다.
    """
    line = f"{n}. {item.get('obj')}"
    des = item.get("des")
    if des:
        line += f" — 뜻: {des}"
    ex = item.get("ex")
    if ex:
        line += f' — 예문: "{ex}"'
    return line


