        #     불변 규칙 5(「1~4문장으로 짧게」)와 정면 충돌한다 — ①만 1~2문장이고
        #     ②③④를 더하면 최소 5~6문장이다.
        #     실측(2026-09-01, 32턴): 중앙 8.6초/126자, 최대 346자/20.6초(≈15문장).
        #   ⇒ **모델이 규칙을 어긴 게 아니라, 시키는 대로 하면 4문장이 안 됐다.**
